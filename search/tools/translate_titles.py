#!/usr/bin/env python3
"""Stage 3 of the paper pipeline: machine-translate the selected titles.

The Japanese title is produced from the verbatim title of the harvested record
by a translation service (Google's public translation endpoint, with
MyMemory as a fallback). Nothing is generated by the model: the translation is
of the registered title text only.
"""

from __future__ import annotations

import argparse
import time
from typing import List, Optional

from paper_common import get_db, get_session

GTX_URL = "https://translate.googleapis.com/translate_a/single"
MYMEMORY_URL = "https://api.mymemory.translated.net/get"
BATCH_SIZE = 8


def translate_batch(session, titles: List[str]) -> Optional[List[str]]:
    joined = "\n".join(titles)
    params = {"client": "gtx", "sl": "en", "tl": "ja", "dt": "t", "q": joined}
    try:
        response = session.get(GTX_URL, params=params, timeout=45)
        if response.status_code != 200:
            return None
        payload = response.json()
    except Exception:  # noqa: BLE001 - network faults are handled by fallback
        return None
    if not payload or not payload[0]:
        return None
    text = "".join(segment[0] for segment in payload[0] if segment and segment[0])
    parts = [p.strip() for p in text.split("\n")]
    if len(parts) != len(titles):
        return None
    return parts


def translate_single(session, title: str) -> Optional[str]:
    try:
        response = session.get(GTX_URL, params={"client": "gtx", "sl": "en", "tl": "ja",
                                                 "dt": "t", "q": title}, timeout=45)
        if response.status_code == 200:
            payload = response.json()
            if payload and payload[0]:
                return "".join(segment[0] for segment in payload[0] if segment and segment[0]).strip()
    except Exception:  # noqa: BLE001 - fall through to the secondary service
        pass
    try:
        response = session.get(MYMEMORY_URL, params={"q": title, "langpair": "en|ja"}, timeout=45)
        if response.status_code == 200:
            payload = response.json()
            translated = payload.get("responseData", {}).get("translatedText")
            if translated:
                return translated.strip()
    except Exception:  # noqa: BLE001 - translation is best effort
        return None
    return None


def main() -> int:
    parser = argparse.ArgumentParser(description="Translate selected paper titles into Japanese")
    parser.add_argument("--limit", type=int, default=0)
    args = parser.parse_args()

    conn = get_db()
    conn.row_factory = __import__("sqlite3").Row
    rows = conn.execute(
        """SELECT s.doi AS doi, p.title AS title
           FROM selected s JOIN papers p ON p.doi = s.doi
           WHERE s.doi NOT IN (SELECT doi FROM translations)
           ORDER BY s.category, s.rank"""
    ).fetchall()
    if args.limit:
        rows = rows[: args.limit]
    print(f"[translate] pending titles: {len(rows)}")

    session = get_session()
    done = 0
    failures = 0
    for start in range(0, len(rows), BATCH_SIZE):
        chunk = rows[start:start + BATCH_SIZE]
        titles = [row["title"] for row in chunk]
        translated = translate_batch(session, titles)
        engine = "google-translate"
        if translated is None:
            translated = []
            engine = "mymemory"
            for title in titles:
                single = translate_single(session, title)
                translated.append(single or "")
                time.sleep(0.05)
        for row, jp in zip(chunk, translated):
            jp = (jp or "").strip()
            if not jp:
                failures += 1
                jp = row["title"]
                engine = "untranslated"
            conn.execute(
                "INSERT OR REPLACE INTO translations (doi, title_ja, engine) VALUES (?,?,?)",
                (row["doi"], jp, engine))
        conn.commit()
        done += len(chunk)
        if (start // BATCH_SIZE) % 25 == 0:
            print(f"[translate] {done}/{len(rows)} (failures so far: {failures})")
            time.sleep(0.4)

    conn.close()
    print(f"[translate] finished: {done} titles, {failures} without translation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
