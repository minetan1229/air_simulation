"""Tests for Issue #98: Finite hinge length_ratio integration and validation.

Verifies:
1. length_ratio represents a finite-length hinge chord segment.
2. In the procedural origami genome, length_ratio is bounded in [0.05, 1.0].
3. For folds acting on a sheet, when length_ratio is altered, the crease segment
   p0 -> p1 properly bounds the hinge chord length.
4. Identifies the current geometric model capability: where full-sheet planar cut
   is used, length_ratio is explicitly validated and documented to prevent
   reward hacking / spurious parameter divergence in GA optimization.
"""

from __future__ import annotations

import math
import pytest
from physics.ga2.genome import (
    HybridFoldGene,
    HybridGenome,
    crease_segment,
    mutate_hybrid,
    random_hybrid_genome,
)
from physics.ga2.stage0 import GeometryFilter, hybrid_to_origami


def test_crease_segment_length_ratio_scaling() -> None:
    """Verifies that crease_segment scales chord length monotonically with length_ratio."""
    origin = (0.5, 0.0)
    angle_deg = 90.0

    p0_full, p1_full = crease_segment(origin, angle_deg, length_ratio=1.0)
    len_full = math.hypot(p1_full[0] - p0_full[0], p1_full[1] - p0_full[1])

    p0_half, p1_half = crease_segment(origin, angle_deg, length_ratio=0.5)
    len_half = math.hypot(p1_half[0] - p0_half[0], p1_half[1] - p0_half[1])

    assert len_half == pytest.approx(0.5 * len_full, rel=1e-5)
    assert p0_full == p0_half


def test_genome_length_ratio_invariants() -> None:
    """Verifies that genes generated by random_hybrid_genome or mutate_hybrid respect bounds."""
    import random
    rng = random.Random(42)

    genome = random_hybrid_genome(rng, min_steps=4, max_steps=6)
    for gene in genome.genes:
        assert 0.05 <= gene.length_ratio <= 1.0

    mutant = mutate_hybrid(genome, rng, rate=0.5)
    for gene in mutant.genes:
        assert 0.05 <= gene.length_ratio <= 1.0


def test_hybrid_to_origami_crease_length_preservation() -> None:
    """Verifies that origami FoldStep receives crease endpoints matching length_ratio."""
    g_full = HybridFoldGene(
        enabled=True,
        origin=(0.5, 0.0),
        crease_angle_deg=90.0,
        length_ratio=1.0,
        fold_angle_deg=30.0,
    )
    g_part = HybridFoldGene(
        enabled=True,
        origin=(0.5, 0.0),
        crease_angle_deg=90.0,
        length_ratio=0.6,
        fold_angle_deg=30.0,
    )

    o_full = hybrid_to_origami(HybridGenome([g_full]))
    o_part = hybrid_to_origami(HybridGenome([g_part]))

    p0_f, p1_f = o_full.steps[0].crease_line
    p0_p, p1_p = o_part.steps[0].crease_line

    len_f = math.hypot(p1_f[0] - p0_f[0], p1_f[1] - p0_f[1])
    len_p = math.hypot(p1_p[0] - p0_p[0], p1_p[1] - p0_p[1])

    assert len_p == pytest.approx(0.6 * len_f, rel=1e-5)


def test_geometry_filter_hot_spot_sensitivity_to_length_ratio() -> None:
    """Hot-spot tear detection depends on actual finite segment overlap and intersection."""
    # Two collinear segments: if length_ratio=1.0 they cross/overlap each other
    g1 = HybridFoldGene(
        enabled=True,
        origin=(0.1, 0.5),
        crease_angle_deg=0.0,
        length_ratio=1.0,
        fold_angle_deg=10.0,
    )
    g2 = HybridFoldGene(
        enabled=True,
        origin=(0.6, 0.5),
        crease_angle_deg=0.0,
        length_ratio=1.0,
        fold_angle_deg=10.0,
    )

    gf = GeometryFilter(paper_gsm=100.0)
    hot_full = gf._hot_spot_count(HybridGenome([g1, g2]))

    # Shorten them so they don't reach each other
    g1_short = HybridFoldGene(
        enabled=True,
        origin=(0.1, 0.5),
        crease_angle_deg=0.0,
        length_ratio=0.2,
        fold_angle_deg=10.0,
    )
    g2_short = HybridFoldGene(
        enabled=True,
        origin=(0.8, 0.5),
        crease_angle_deg=0.0,
        length_ratio=0.2,
        fold_angle_deg=10.0,
    )
    hot_short = gf._hot_spot_count(HybridGenome([g1_short, g2_short]))

    assert hot_full > hot_short
