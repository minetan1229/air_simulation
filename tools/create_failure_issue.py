"""Create or update a GitHub issue when CI test/workflow fails."""

import json
import os
import sys
import urllib.error
import urllib.request
from typing import Any, Dict, List, Optional


def get_env_var(name: str, default: str = "") -> str:
    return os.environ.get(name, default).strip()


def github_api_request(
    endpoint: str,
    method: str = "GET",
    data: Optional[Dict[str, Any]] = None,
    token: str = "",
) -> Any:
    api_url = f"https://api.github.com{endpoint}"
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "CI-Failure-Reporter",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    body_bytes = json.dumps(data).encode("utf-8") if data is not None else None
    req = urllib.request.Request(api_url, data=body_bytes, headers=headers, method=method)

    with urllib.request.urlopen(req, timeout=15) as resp:
        res_data = resp.read().decode("utf-8")
        if res_data:
            return json.loads(res_data)
        return None


def find_existing_open_issue(repo: str, title: str, token: str) -> Optional[Dict[str, Any]]:
    endpoint = f"/repos/{repo}/issues?state=open&labels=ci-failure&per_page=50"
    try:
        issues: List[Dict[str, Any]] = github_api_request(endpoint, method="GET", token=token)
        for issue in issues:
            # Check if title matches or pull_request key is absent (pure issue)
            if "pull_request" not in issue and issue.get("title") == title:
                return issue
    except Exception as exc:
        print(f"Warning: Failed to search existing issues: {exc}", file=sys.stderr)
    return None


def create_or_update_issue() -> int:
    token = get_env_var("GITHUB_TOKEN")
    if not token:
        print("Notice: GITHUB_TOKEN not configured. Skipping GitHub issue creation.", file=sys.stderr)
        return 0

    repo = get_env_var("GITHUB_REPOSITORY")
    if not repo:
        print("Warning: GITHUB_REPOSITORY is empty. Cannot create issue.", file=sys.stderr)
        return 0

    workflow_name = get_env_var("GITHUB_WORKFLOW", "CI Verification")
    run_id = get_env_var("GITHUB_RUN_ID", "unknown")
    run_number = get_env_var("GITHUB_RUN_NUMBER", "unknown")
    ref = get_env_var("GITHUB_REF_NAME", get_env_var("GITHUB_REF", "unknown"))
    sha = get_env_var("GITHUB_SHA", "unknown")[:7]
    server_url = get_env_var("GITHUB_SERVER_URL", "https://github.com")
    run_url = f"{server_url}/{repo}/actions/runs/{run_id}"

    title = f"🚨 CI Failure: {workflow_name} on {ref}"

    summary_file = get_env_var("TEST_SUMMARY_FILE")
    details = ""
    if summary_file and os.path.exists(summary_file):
        try:
            with open(summary_file, "r", encoding="utf-8") as f:
                details = f.read().strip()
        except Exception as e:
            details = f"Failed to read test summary file: {e}"

    if not details:
        details = "Pytest or CI step exited with failure. Check GitHub Actions run logs for details."

    body = (
        f"## ❌ CI Workflow Failed\n\n"
        f"- **Workflow:** {workflow_name}\n"
        f"- **Branch / Ref:** `{ref}`\n"
        f"- **Commit:** `{sha}`\n"
        f"- **Run:** [#{run_number}]({run_url})\n\n"
        f"### Failure Details\n\n"
        f"```text\n{details[:4000]}\n```\n\n"
        f"---\n"
        f"*This issue was automatically generated by GitHub Actions upon pytest/verification failure.*"
    )

    try:
        existing = find_existing_open_issue(repo, title, token)
        if existing:
            issue_number = existing["number"]
            print(f"Existing open issue found: #{issue_number}. Adding comment...")
            comment_endpoint = f"/repos/{repo}/issues/{issue_number}/comments"
            comment_body = {
                "body": (
                    f"### 🔁 CI Failure recurred in run [#{run_number}]({run_url}) (`{sha}`)\n\n"
                    f"```text\n{details[:2000]}\n```"
                )
            }
            github_api_request(comment_endpoint, method="POST", data=comment_body, token=token)
            print(f"Successfully commented on issue #{issue_number}")
        else:
            print(f"Creating new GitHub issue in {repo}...")
            endpoint = f"/repos/{repo}/issues"
            payload = {
                "title": title,
                "body": body,
                "labels": ["ci-failure", "bug"],
            }
            res = github_api_request(endpoint, method="POST", data=payload, token=token)
            print(f"Successfully created issue #{res.get('number')}: {res.get('html_url')}")
    except urllib.error.HTTPError as exc:
        err_msg = exc.read().decode("utf-8") if exc.fp else str(exc)
        print(f"Error creating/updating issue (HTTP {exc.code}): {err_msg}", file=sys.stderr)
        return 0  # Do not break the pipeline itself if issue creation fails
    except Exception as exc:
        print(f"Error creating/updating issue: {exc}", file=sys.stderr)
        return 0

    return 0


if __name__ == "__main__":
    sys.exit(create_or_update_issue())
